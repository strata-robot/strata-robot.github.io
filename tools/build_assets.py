"""Build web assets for the STRATA project page from the paper figures and episode dumps.

Usage: python3 tools/build_assets.py   (run from strata_web/)
Inputs: UQ_20261010/overleaf_uq_tridet/figures/paper/*.png, p1/fig_process/ep*.json + frames_*/
Outputs: static/img/*.webp, static/img/frames/<ep>/*.jpg, static/data/episodes.js
"""
import json, os, re, shutil
from PIL import Image

ROOT = "/mnt/ssd-storage/trinhpn"
FIG = f"{ROOT}/UQ_20261010/overleaf_uq_tridet/figures/paper"
PROC = f"{ROOT}/p1/fig_process"
OUT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
IMG = f"{OUT}/static/img"
os.makedirs(IMG, exist_ok=True)
os.makedirs(f"{OUT}/static/data", exist_ok=True)


def save(im, name, width):
    im = im.convert("RGB")
    if im.width > width:
        im = im.resize((width, round(im.height * width / im.width)), Image.LANCZOS)
    im.save(f"{IMG}/{name}", "WEBP", quality=88, method=6)
    print(name, im.size, os.path.getsize(f"{IMG}/{name}") // 1024, "KB")


save(Image.open(f"{FIG}/fig_overview.png"), "fig_overview.webp", 2200)
save(Image.open(f"{FIG}/fig_process.png"), "fig_process.webp", 2000)
save(Image.open(f"{FIG}/fig_process_ex2.png"), "fig_process_ex2.webp", 2000)
save(Image.open(f"{FIG}/fig_strata_bars_v2.png"), "fig_strata_bars.webp", 1200)
m = Image.open(f"{FIG}/fig_tvf_focus.png")
CUT = int(os.environ.get("CUT", "865"))  # gap between panel (a) TVF and panel (b) FOCUS
save(m.crop((0, 0, m.width, CUT)), "fig_tvf.webp", 2200)
save(m.crop((0, CUT, m.width, m.height)), "fig_focus.webp", 2200)
save(m, "fig_tvf_focus.webp", 2200)

SHORT = {
    "27113": dict(name="Pack a desk lamp", labels=["Pick lamp", "Place lamp", "Pick cable", "Place cable",
              "Press lids 1–2", "Adjust box", "Press lid 3", "Press lid 4", "Align lid 5", "Insert lid 5"]),
    "20397": dict(name="Open a tea canister", labels=["Pick canister", "Unscrew lid", "Place lid", "Take out tea bag",
              "Tea bag into mug", "Pick lid", "Screw lid", "Place canister"]),
}
eps = []
for ep, meta in SHORT.items():
    d = json.load(open(f"{PROC}/ep{ep}.json"))
    fdir = f"{PROC}/frames_{ep}"
    os.makedirs(f"{IMG}/frames/{ep}", exist_ok=True)
    frames = []
    for f in sorted(os.listdir(fdir)):
        mm = re.match(r"([hk])_([\d.]+)\.jpg$", f)
        if not mm:
            continue
        shutil.copy(f"{fdir}/{f}", f"{IMG}/frames/{ep}/{f}")
        frames.append(dict(t=float(mm.group(2)), src=f"static/img/frames/{ep}/{f}", key=mm.group(1) == "k"))
    frames.sort(key=lambda x: x["t"])
    tel = []
    for ch in d["tel"]:
        ch = ch[::2]  # 10 Hz -> 5 Hz
        lo, hi = min(ch), max(ch)
        tel.append([round((v - lo) / (hi - lo + 1e-9), 3) for v in ch])
    assert len(d["segments"]) == len(meta["labels"]), ep
    eps.append(dict(
        id=ep, task=d["task"], name=meta["name"], trajectory=d["trajectory"], duration=round(d["high"], 2),
        truth=[round(x, 2) for x in d["truth"]],
        segments=[dict(s=round(s["start"], 2), e=round(s["end"], 2), skill=s["skill"], label=lab,
                       text=s["instruction"]) for s, lab in zip(d["segments"], meta["labels"])],
        cand=[dict(t=round(c["t"], 2), h=round(c["h"], 3), p=round(c["p"], 3), prop=bool(c["prop"]),
                   y=int(c["y"])) for c in d["cand"]],
        tel_dt=0.2, tel=tel, frames=frames))
js = ("// Generated by tools/build_assets.py from p1/fig_process/ep*.json (AgiBot World 2026 RL held-out tasks,\n"
      "// FOCUS = unified model, draw 0, five labelled recordings). Do not edit by hand.\n"
      "window.STRATA_EPISODES = " + json.dumps(eps, separators=(",", ":"), ensure_ascii=False) + ";\n")
open(f"{OUT}/static/data/episodes.js", "w").write(js)
print("episodes.js", len(js) // 1024, "KB")
