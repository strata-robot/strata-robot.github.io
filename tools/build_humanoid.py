"""Dataset example for the humanoid section: one cloth-folding recording with a single-colour (olive, unprinted) shirt.

Writes static/video/humanoid_fold.mp4 (+ .jpg poster) and static/data/humanoid.js (window.STRATA_HUMANOID).
Video = torso camera (large) + head and left-wrist cameras, 2x speed, 15 fps. The right-wrist camera is left out:
it catches a bystander in the background. Annotation = the recording's own language segments
(meta/lerobot_annotations.json); telemetry = the 6 of 31 joint-state channels with the largest std, 5 Hz.
    python3 tools/build_humanoid.py
"""
import json
import subprocess
from pathlib import Path

import numpy as np
import pyarrow.parquet as pq

D = "/mnt/ceph-cold-storage/temporary/hiephn/m2v2_50h"
REL = "m2v2.2#2/task_01/lerobot_dataset_1019_1025/recording_M2v2.2#2_20261021_0057_0"   # chosen 2026-11-26
OUT = Path(__file__).resolve().parent.parent / "static"
SPEED = 2
SHORT = {  # sub-task sentence (start) -> short label
    "The garment is being laid out": "Lay out", "Grasp the near side": "Grasp near side",
    "Fold the near side": "Fold near side", "Smooth the fold": "Smooth fold", "Align and smooth": "Align & smooth",
    "Grasp the far side": "Grasp far side", "Fold the far side": "Fold far side",
    "Grasp the right hand side": "Grasp right side", "Fold the right hand side": "Fold right side",
    "Grasp the left hand side": "Grasp left side", "Fold the left hand side": "Fold left side",
    "The robot is not perform": "Idle", "No action": "Idle",
}


def short(text):
    for k, v in SHORT.items():
        if text.startswith(k):
            return v
    return text.rstrip(".")[:18]


def cam(name):
    return f"{D}/{REL}/videos/observation.images.{name}/chunk-000/file-000.mp4"


if __name__ == "__main__":
    rec = next(r for r in json.load(open(f"{D}/manifest.json"))["recordings"] if r["relative"] == REL)
    ep = json.load(open(f"{D}/{REL}/meta/lerobot_annotations.json"))["episodes"][0]
    segs = [dict(s=round(s["start_time"], 2), e=round(s["end_time"], 2), text=s["data"]["subtask"],
                 label=short(s["data"]["subtask"])) for s in ep["spans"] if s["kind"] == "language_segment"]
    kinds = []
    for g in segs:
        if g["label"] not in kinds:
            kinds.append(g["label"])
    for g in segs:
        g["k"] = kinds.index(g["label"])
    st = np.stack(pq.read_table(f"{D}/{REL}/data/chunk-000/file-000.parquet", columns=["observation.state"])
                  .column(0).to_numpy(zero_copy_only=False)).astype(float)
    fps = rec["fps"]
    step = max(1, int(round(fps / 5)))
    st = st[::step]
    keep = np.argsort(-st.std(0))[:6]
    tel = []
    for ch in st[:, keep].T:
        lo, hi = ch.min(), ch.max()
        tel.append([round(float((v - lo) / (hi - lo + 1e-9)), 3) for v in ch])
    data = dict(robot=rec["robot"], duration=round(rec["duration"], 2), task=ep["task_declared"],
                status=ep["episode_status"], segments=segs, kinds=kinds, tel=tel, tel_dt=round(step / fps, 4),
                dof=int(st.shape[1]), video="static/video/humanoid_fold.mp4", poster="static/video/humanoid_fold.jpg",
                speed=SPEED, boundaries=sum(1 for a, b in zip(segs, segs[1:])))
    (OUT / "data" / "humanoid.js").write_text(
        "// Generated by tools/build_humanoid.py from the humanoid dataset release (m2v2_50h). Do not edit by hand.\n"
        "window.STRATA_HUMANOID = " + json.dumps(data, separators=(",", ":"), ensure_ascii=False) + ";\n")
    vid = OUT / "video" / "humanoid_fold.mp4"
    flt = (f"[0:v]scale=640:400,setsar=1[t];[1:v]scale=320:200,setsar=1[h];"
           f"[2:v]scale=320:240,crop=320:200,setsar=1[l];[h][l]vstack[r];[t][r]hstack,setpts=PTS/{SPEED},fps=15[v]")
    subprocess.run(["ffmpeg", "-loglevel", "error", "-y", "-i", cam("cam_torso"), "-i", cam("cam_head"),
                    "-i", cam("cam_left_wrist"), "-filter_complex", flt, "-map", "[v]", "-an",
                    "-c:v", "libx264", "-preset", "slow", "-crf", "28", "-pix_fmt", "yuv420p", "-movflags", "+faststart",
                    "-threads", "4", str(vid)], check=True)
    subprocess.run(["ffmpeg", "-loglevel", "error", "-y", "-ss", "3", "-i", str(vid), "-frames:v", "1", "-q:v", "4",
                    str(OUT / "video" / "humanoid_fold.jpg")], check=True)
    print(f"{rec['robot']} {rec['duration']:.1f}s, {len(segs)} segments ({data['boundaries']} boundaries), "
          f"{len(kinds)} sub-task types, {data['dof']}-D state; video {vid.stat().st_size // 1024} KB")
    for g in segs:
        print(f"  {g['s']:6.1f}-{g['e']:6.1f} {g['label']:<16} {g['text'][:80]}")
